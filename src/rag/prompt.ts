import type { ChatMessage } from "../llm/index.ts";
import type { SearchResult } from "../vectorstore/index.ts";

// Фраза, которой модель должна отвечать, если во фрагментах нет ответа
export const NO_ANSWER_PHRASE = "В найденных документах нет ответа на этот вопрос";

const SYSTEM_PROMPT = `Ты — справочная система по локальным нормативным документам ГУАП (Санкт-Петербургского государственного университета аэрокосмического приборостроения).

Правила:
1. Отвечай только на основе фрагментов документов из сообщения пользователя. Не используй собственные знания.
2. В конце каждого предложения указывай в квадратных скобках номер фрагмента, на котором оно основано: [1], [2]. Если предложение основано на нескольких фрагментах, пиши каждый номер отдельно: [1][3].
3. Числа, сроки, даты и названия бери из фрагментов без изменений.
4. Если во фрагментах есть ответ только на часть вопроса, ответь на эту часть и коротко укажи, чего в документах нет.
5. Если в вопросе есть неверное предположение (например, о сроке или количестве), не соглашайся с ним, а приведи то, что сказано во фрагментах.
6. Только если во фрагментах нет ничего по теме вопроса, ответь одной фразой: «${NO_ANSWER_PHRASE}». Ничего не додумывай.
7. Отвечай на русском языке, кратко и по существу: без вступлений, без повторов, без итоговых выводов и без отдельной строки со списком ссылок в конце.`;

const formatFragment = ({ payload }: SearchResult, index: number): string => {
    const location = payload.clause ? `п. ${payload.clause}` : (payload.section ?? "");
    return `[${index + 1}] ${payload.title} — ${location}\n${payload.text}`;
};

export const buildMessages = (question: string, results: SearchResult[]): ChatMessage[] => [
    { role: "system", content: SYSTEM_PROMPT },
    {
        role: "user",
        content: `Фрагменты документов:\n\n${results.map(formatFragment).join("\n\n")}\n\nВопрос: ${question}`,
    },
];
